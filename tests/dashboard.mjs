assert.match(html,/Sem prazo/);
assert.match(html,/Aguardar orçamento/);
assert.match(html,/Adiado/);
assert.doesNotMatch(html,/>Fechado</);
assert.doesNotMatch(html,/>Cancelado</);
assert.doesNotMatch(html,/>Contacto</);
